# Cuts the three variable fonts down to what the site actually uses, so they download faster.
# Only Latin and Latin Extended are kept, and each font's axes are narrowed to the weights and widths the CSS asks for.
# Writes src/assets/fonts/*.woff2 and src/styles/fonts.css. Rerun after changing which weights the CSS uses:
#   pip install fonttools brotli
#   python scripts/fonts.py
import re
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
FONTSOURCE = ROOT / 'node_modules' / '@fontsource-variable'
OUT = ROOT / 'src' / 'assets' / 'fonts'

FONTS = [
    # family, fontsource css, file stem, axes kept
    ('Archivo Variable', 'archivo/wdth.css', 'archivo', {'wght': (600, 800), 'wdth': (72, 100)}),
    ('Geist Variable', 'geist/index.css', 'geist', {'wght': (400, 700)}),
    ('JetBrains Mono Variable', 'jetbrains-mono/index.css', 'jetbrains-mono', {'wght': (400, 700)}),
]
SUBSETS = ['latin-ext', 'latin']  # latin last, so it wins where the ranges overlap


def faces(css: str):
    for block in re.findall(r'@font-face\s*{([^}]*)}', css):
        src = re.search(r'url\(\./files/([^)]+)\)', block).group(1)
        yield src, re.search(r'unicode-range:\s*([^;]+);', block).group(1).strip()


OUT.mkdir(parents=True, exist_ok=True)
css = ['/* Generated by scripts/fonts.py. */']
for family, sheet, stem, axes in FONTS:
    ranges = dict(faces((FONTSOURCE / sheet).read_text()))
    for subset in SUBSETS:
        name = next(f for f in ranges if re.search(rf'-{subset}-(wdth|wght)-normal\.woff2$', f))
        font = instancer.instantiateVariableFont(TTFont(FONTSOURCE / sheet.split('/')[0] / 'files' / name), axes)
        font.flavor = 'woff2'
        out = OUT / f'{stem}-{subset}.woff2'
        font.save(out)
        print(f'{out.name}: {(FONTSOURCE / sheet.split("/")[0] / "files" / name).stat().st_size} -> {out.stat().st_size}')
        weight = '{} {}'.format(*axes['wght'])
        stretch = 'font-stretch: {}% {}%;\n  '.format(*axes['wdth']) if 'wdth' in axes else ''
        css.append(
            f"@font-face {{\n  font-family: '{family}';\n  font-style: normal;\n  font-display: swap;\n"
            f"  font-weight: {weight};\n  {stretch}src: url('../assets/fonts/{out.name}') format('woff2-variations');\n"
            f'  unicode-range: {ranges[name]};\n}}'
        )
(ROOT / 'src' / 'styles' / 'fonts.css').write_text('\n'.join(css) + '\n', newline='\n')
